func jsonBytes(t *testing.T, value any) []byte {
	t.Helper()
	data, err := json.Marshal(value)
	if err != nil {
		t.Fatal(err)
	}
	return data
}

// newFixture builds the real governed chain: CANDIDATE → ReviewEvidence →
// ReviewReplay → BuildFromMappingDefinition → engineer approval.
func newFixture(t *testing.T) fixture {
	t.Helper()
	dir := t.TempDir()
	m, err := mapping.New("registry.fixture", "mapping-3", "HL7_V2", 5, "PULSE", "bpm",
		"pulse_rate", "bpm", "explicit registry fixture claim", "fixture author")
	if err != nil {
		t.Fatal(err)
	}
	m.ParserIdentity, m.DeviceFingerprint, m.DeviceIdentityRef = "generic_hl7_v2", "fixture-fp", "fixture-device"
	bundle := evidence.ClaimReview{Claim: m.Claim(), Evidence: []evidence.Evidence{
		{Type: "VENDOR_MANUAL", Ref: "fixture:manual"},
		{Type: "SIMULATOR_LOG", Ref: "fixture:measurement"},
	}}
	evidencePath := filepath.Join(dir, "evidence.json")
	if err := os.WriteFile(evidencePath, jsonBytes(t, bundle), 0600); err != nil {
		t.Fatal(err)
	}
	if err := mapping.ReviewEvidence(m, evidencePath, filepath.Join(dir, "evidence-report.json")); err != nil {
		t.Fatal(err)
	}
	if err := os.WriteFile(filepath.Join(dir, "raw_stream.bin"),
		[]byte("MSH|^~\\&|fixture\nOBX|1|NM|PULSE||73|bpm\n"), 0600); err != nil {
		t.Fatal(err)
	}
	truth := filepath.Join(dir, "ground-truth.json")
	if err := os.WriteFile(truth, []byte(`{"pulse_rate":73}`), 0600); err != nil {
		t.Fatal(err)
	}
	if _, err := mapping.ReviewReplay(m, dir, 2, replay.ReplayOptions{GroundTruthPath: truth},
		filepath.Join(dir, "replay-report.json")); err != nil {
		t.Fatal(err)
	}
	p, err := profilebuilder.BuildFromMappingDefinition(m, "Fixture Maker", "Device R", "serial", "fw-2",
		filepath.Join(dir, "profile"), "profile-4")
	if err != nil {
		t.Fatal(err)
	}
	a, err := approval.Review(&p, m, "engineer:registry", approval.DecisionApprove)
	if err != nil {
		t.Fatal(err)
	}
	publicKey, issuerKey, err := ed25519.GenerateKey(rand.Reader)
	if err != nil {
		t.Fatal(err)
	}
	return fixture{candidate: &p, mapping: m, approval: a, publicKey: publicKey, issuerKey: issuerKey}
}

func admit(t *testing.T, f fixture, sequence uint64) *registry.Attestation {
	t.Helper()
	a, err := registry.Admit(f.candidate, f.mapping, f.approval, f.issuerKey, keyID, sequence)
	if err != nil || a == nil {
		t.Fatalf("admission failed: %v %v", a, err)
	}
	return a
}

func TestAdmitLiveGovernedChain(t *testing.T) {
	f := newFixture(t)
	beforeCandidate, beforeMapping := string(jsonBytes(t, f.candidate)), string(jsonBytes(t, f.mapping))
	beforeApproval := string(jsonBytes(t, f.approval))
	start := time.Now().UTC()
	a := admit(t, f, 7)
	end := time.Now().UTC()

	if a.AdmissionStatus != registry.StatusRegistryAdmitted || a.SchemaVersion != registry.SchemaV1 {
		t.Fatalf("unexpected admission result: %+v", a)
	}
	if a.ProfileID != f.candidate.ProfileID || a.ProfileVersion != f.candidate.Version ||
		a.MappingIdentity != f.mapping.MappingIdentity || a.MappingVersion != f.mapping.MappingVersion ||
		a.EvidenceReference != f.mapping.EvidenceGateReportRef ||
		!a.ReplayValidatedAt.Equal(f.mapping.ReplayValidatedAt) ||
		a.MappingProvenance != f.mapping.Provenance || a.ProvenanceAuthor != f.mapping.ProvenanceAuthor ||
		a.ApproverIdentity != f.approval.ApproverIdentity ||
		!a.ApprovalTimestamp.Equal(f.approval.ApprovedAt) ||
		a.CandidateDigest != f.approval.CandidateDigest ||
		a.IssuerKeyID != keyID || a.Sequence != 7 {
		t.Fatalf("incorrect admission binding: %+v", a)
	}
	if a.IssuedAt.IsZero() || a.IssuedAt.Location() != time.UTC || a.IssuedAt.Before(start) || a.IssuedAt.After(end) {
		t.Fatalf("IssuedAt not generated by admission in UTC: %v", a.IssuedAt)
	}
	if err := registry.VerifyAttestation(a, f.candidate, f.publicKey, keyID); err != nil {
		t.Fatalf("fresh attestation rejected: %v", err)
	}
	// Governed inputs keep their own statuses; admission promotes nothing.
	if f.candidate.Status != "CANDIDATE" || f.candidate.ValidationStatus != "CANDIDATE" {
		t.Fatal("candidate promoted by admission")
	}
	if f.approval.ApprovalStatus != approval.StatusEngineerApproved || f.approval.Decision != approval.DecisionApprove {
		t.Fatal("approval changed by admission")
	}
	if err := f.approval.Validate(f.candidate, f.mapping); err != nil {
		t.Fatalf("approval authority damaged: %v", err)
	}
	if string(jsonBytes(t, f.candidate)) != beforeCandidate || string(jsonBytes(t, f.mapping)) != beforeMapping ||
		string(jsonBytes(t, f.approval)) != beforeApproval {
		t.Fatal("admission mutated governed input")
	}
	status, err := f.mapping.Status()
	if err != nil || status != mapping.StatusReplayValidated {
		t.Fatalf("mapping status=%s err=%v", status, err)
	}
	for _, forbidden := range []string{"VERIFIED", "REAL_DEVICE_VALIDATED", "PRODUCTION_VALIDATED", "REGISTERED", "CONNECTED", "ACTIVE"} {
		if strings.Contains(string(jsonBytes(t, a)), forbidden) {
			t.Fatalf("attestation emitted advanced status %s", forbidden)
		}
	}
}

// Verification must work from persisted bytes alone: no live mapping, approval or process.
func TestVerifyAfterLiveAuthorityIsGone(t *testing.T) {
	persisted, candidateJSON, publicKey := func() ([]byte, []byte, ed25519.PublicKey) {
		f := newFixture(t)
		a := admit(t, f, 3)
		return jsonBytes(t, a), jsonBytes(t, f.candidate), f.publicKey
	}()

	var restored registry.Attestation
	if err := json.Unmarshal(persisted, &restored); err != nil {
		t.Fatal(err)
	}
	var candidate profilebuilder.Profile
	if err := json.Unmarshal(candidateJSON, &candidate); err != nil {
		t.Fatal(err)
	}
	if err := registry.VerifyAttestation(&restored, &candidate, publicKey, keyID); err != nil {
		t.Fatalf("persisted attestation rejected: %v", err)
	}
	// Approval authority cannot be restored, yet verification above already succeeded.
	var importedApproval approval.Approval
	if err := json.Unmarshal([]byte(`{"approval_status":"ENGINEER_APPROVED"}`), &importedApproval); err == nil {
		t.Fatal("approval authority was importable")
	}
	var importedMapping mapping.MappingDefinition
	if err := json.Unmarshal([]byte(`{"status":"REPLAY_VALIDATED"}`), &importedMapping); err == nil {
		t.Fatal("replay-validated mapping authority was importable")
	}
}

