// Golden test: freezes the canonical signed byte construction. Changing the layout,
// field order or field set breaks this test and requires a new SchemaVersion.
func TestCanonicalPayloadIsFrozenAndDeterministic(t *testing.T) {
	fixed := time.Date(2026, 2, 3, 4, 5, 6, 7, time.UTC)
	_, issuerKey, err := ed25519.GenerateKey(rand.Reader)
	if err != nil {
		t.Fatal(err)
	}
	a := registry.Attestation{
		SchemaVersion: registry.SchemaV1, AdmissionStatus: registry.StatusRegistryAdmitted,
		ProfileID: "Maker_Device_fw_vp1", ProfileVersion: "p1",
		CandidateDigest: strings.Repeat("ab", 32),
		MappingIdentity: "map.id", MappingVersion: "m1",
		EvidenceReference: "/tmp/evidence-report.json", ReplayValidatedAt: fixed,
		MappingProvenance: "explicit claim", ProvenanceAuthor: "author",
		ApproverIdentity: "engineer", ApprovalTimestamp: fixed.Add(time.Minute),
		IssuerKeyID: keyID, IssuedAt: fixed.Add(2 * time.Minute), Sequence: 11,
	}
	want := "OTRIS-REGISTRY-ADMISSION\n" +
		"27:otris.registry.admission.v1\n" +
		"17:REGISTRY_ADMITTED\n" +
		"19:Maker_Device_fw_vp1\n" +
		"2:p1\n" +
		"64:" + strings.Repeat("ab", 32) + "\n" +
		"6:map.id\n" +
		"2:m1\n" +
		"25:/tmp/evidence-report.json\n" +
		"30:2026-02-03T04:05:06.000000007Z\n" +
		"14:explicit claim\n" +
		"6:author\n" +
		"8:engineer\n" +
		"30:2026-02-03T04:06:06.000000007Z\n" +
		"20:registry-issuer-test\n" +
		"30:2026-02-03T04:07:06.000000007Z\n" +
		"2:11\n"

	// Sign the expected bytes with an independent signer; if the package's canonical
	// construction differed in any byte, verification below would fail.
	a.Signature = hex.EncodeToString(ed25519.Sign(issuerKey, []byte(want)))
	publicKey := ed25519.PublicKey(issuerKey[32:])

	digest := strings.Repeat("ab", 32)
	candidate := &profilebuilder.Profile{}
	if err := registry.VerifyAttestation(&a, candidate, publicKey, keyID); err == nil {
		t.Fatal("empty candidate matched the frozen digest")
	} else if !strings.Contains(err.Error(), "candidate does not match") {
		t.Fatalf("canonical bytes drifted from the frozen layout: %v (digest %s)", err, digest)
	}

	// Determinism: same values, non-UTC zones and repeated calls produce one signature.
	shifted := a
	shifted.ReplayValidatedAt = fixed.In(time.FixedZone("UTC+7", 7*3600))
	shifted.ApprovalTimestamp = a.ApprovalTimestamp.In(time.FixedZone("UTC-3", -3*3600))
	first := hex.EncodeToString(ed25519.Sign(issuerKey, []byte(want)))
	for _, candidateAttestation := range []registry.Attestation{a, shifted} {
		if err := registry.VerifyAttestation(&candidateAttestation, candidate, publicKey, keyID); err == nil ||
			!strings.Contains(err.Error(), "candidate does not match") {
			t.Fatalf("zone-shifted or repeated canonical bytes changed: %v", err)
		}
	}
	if second := hex.EncodeToString(ed25519.Sign(issuerKey, []byte(want))); first != second {
		t.Fatal("signing the frozen payload is not deterministic")
	}

	// Length prefixes must prevent a shifted field boundary from forging identical bytes.
	shiftLeft, shiftRight := a, a
	shiftLeft.ProfileID, shiftLeft.ProfileVersion = "Maker_Device_fw_vp", "1p1"
	shiftRight.MappingIdentity, shiftRight.MappingVersion = "map.idm", "1"
	for _, forged := range []registry.Attestation{shiftLeft, shiftRight} {
		forged.Signature = a.Signature
		if err := registry.VerifyAttestation(&forged, candidate, publicKey, keyID); err == nil ||
			strings.Contains(err.Error(), "candidate does not match") {
			t.Fatalf("field boundary shift produced accepted payload: %v", err)
		}
	}
}

// Sequence must be inside the signed bytes, not merely reported alongside them.
func TestSequenceIsSignedAndMonotonicityIsNotProven(t *testing.T) {
	f := newFixture(t)
	older := admit(t, f, 1)
	newer, err := registry.Admit(f.candidate, f.mapping, f.approval, f.issuerKey, keyID, 2)
	if err != nil {
		t.Fatal(err)
	}
	if older.Signature == newer.Signature {
		t.Fatal("sequence is not part of the signed payload")
	}
	swapped := *older
	swapped.Sequence = newer.Sequence
	if err := registry.VerifyAttestation(&swapped, f.candidate, f.publicKey, keyID); err == nil {
		t.Fatal("sequence substitution verified")
	}
	// Documented limitation: both attestations verify. Cryptography proves authenticity,
	// not freshness. A persistent registry must enforce accepted-sequence policy.
	for _, a := range []*registry.Attestation{older, newer} {
		if err := registry.VerifyAttestation(a, f.candidate, f.publicKey, keyID); err != nil {
			t.Fatalf("sequence %d rejected: %v", a.Sequence, err)
		}
	}
	if fmt.Sprint(older.Sequence, newer.Sequence) != "1 2" {
		t.Fatal("unexpected fixture sequences")
	}
}
